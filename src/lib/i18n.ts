const tables: Record<UiLocale, TranslationTable> = { en, vi };

export function resolveUiLocale(
  setting: UiLocaleSetting,
  osLocale: string,
): UiLocale {
  if (setting !== "system") return setting;
  return osLocale.toLowerCase().startsWith("vi") ? "vi" : "en";
}

const builtInProfileKeys: Record<string, TranslationKey> = {
  raw: "settings.profileRaw",
  natural: "settings.profileNatural",
  email: "settings.profileEmail",
  summary: "settings.profileSummary",
  code: "settings.profileCode",
};

export function promptProfileLabel(
  locale: UiLocale,
  id: string,
  fallback: string,
): string {
  const key = builtInProfileKeys[id];
  return key ? t(locale, key) : fallback;
}

export function t(
  locale: UiLocale,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const template = tables[locale][key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}
